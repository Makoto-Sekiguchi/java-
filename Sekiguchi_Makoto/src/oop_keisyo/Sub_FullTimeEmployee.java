package oop_keisyo;

public class Sub_FullTimeEmployee extends Employee_abstract{
	private static final int HOURLY_RATE = 1200;
	
	public Sub_FullTimeEmployee (String id, String name) {//コンストラクタ
		super(id, name);
	}
	
	@Override//オーバーライドを宣言し、抽象クラスの抽象メソッドを実装する。
	public int calculateDailyWage(int hoursWorked) {
		int regularHours = 8;
		double wage = regularHours * HOURLY_RATE;
		
		if (hoursWorked == regularHours) {
			
			return (int) wage;//勤務時間が定時時間なら定時の給料をそのまま返す。
		} else {
			double overTimeRate = 1.25;//残業時の給料は1.25倍される
			double overTimeHours = hoursWorked - regularHours;//残業時間=総労働時間-定時
			double overTimeWage = HOURLY_RATE * overTimeRate * overTimeHours;//残業分の賃金(=本来の時給に残業の賃金割合と残業時間をかけたもの)
			
			double totalWage = wage + overTimeWage;
			return (int) totalWage;
		}
	}
		
}		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
	

